insert into public.permissions (key, name, description, group_name, surface, sort_order)
values (
  'support.chat.manage',
  'Manage customer chats',
  'Read and reply to customer conversations.',
  'Customer support',
  'admin',
  70
)
on conflict (key) do nothing;

insert into public.role_permissions (role_id, permission_key)
select r.id, 'support.chat.manage'
from public.roles r
where r.scope = 'staff' and not r.is_full_access
on conflict (role_id, permission_key) do nothing;

create or replace function public.grant_support_chat_to_staff_role()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if new.scope = 'staff' and not new.is_full_access then
    insert into public.role_permissions (role_id, permission_key)
    values (new.id, 'support.chat.manage')
    on conflict (role_id, permission_key) do nothing;
  end if;
  return new;
end;
$$;

revoke all on function public.grant_support_chat_to_staff_role()
  from public, anon, authenticated;

create trigger roles_grant_support_chat_access
  after insert on public.roles
  for each row execute function public.grant_support_chat_to_staff_role();

create table public.support_chat_threads (
  id uuid primary key default gen_random_uuid(),
  customer_kind text not null check (customer_kind in ('account', 'guest')),
  customer_user_id uuid references public.users(id) on delete set null,
  customer_name text not null check (length(btrim(customer_name)) between 1 and 120),
  guest_email text,
  guest_email_verified_at timestamptz,
  guest_phone text,
  status text not null default 'open' check (status in ('open', 'resolved')),
  last_message_at timestamptz not null default timezone('utc'::text, now()),
  resolved_at timestamptz,
  resolved_by uuid references public.users(id) on delete set null,
  created_at timestamptz not null default timezone('utc'::text, now()),
  updated_at timestamptz not null default timezone('utc'::text, now()),
  check (
    (customer_kind = 'account' and guest_email is null and guest_phone is null)
    or (
      customer_kind = 'guest'
      and customer_user_id is null
      and (
        (
          guest_email is not null
          and guest_phone is null
          and guest_email = lower(btrim(guest_email))
          and guest_email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
        )
        or (
          guest_email is null
          and guest_phone is not null
          and guest_phone ~ '^\+?[0-9][0-9() .-]{5,23}$'
          and length(regexp_replace(guest_phone, '[^0-9]', '', 'g')) between 7 and 15
        )
      )
    )
  ),
  check (
    (status = 'open' and resolved_at is null and resolved_by is null)
    or (status = 'resolved' and resolved_at is not null)
  )
);

create unique index support_chat_threads_account_user_uidx
  on public.support_chat_threads (customer_user_id)
  where customer_user_id is not null;
create unique index support_chat_threads_guest_email_uidx
  on public.support_chat_threads (lower(guest_email))
  where guest_email is not null;
create index support_chat_threads_inbox_idx
  on public.support_chat_threads (last_message_at desc, id desc);

create table public.support_chat_messages (
  id uuid primary key default gen_random_uuid(),
  thread_id uuid not null references public.support_chat_threads(id) on delete cascade,
  sender_role text not null check (sender_role in ('customer', 'staff')),
  sender_user_id uuid references public.users(id) on delete set null,
  sender_name text not null check (length(btrim(sender_name)) between 1 and 120),
  body text,
  deleted_at timestamptz,
  deleted_by_user_id uuid references public.users(id) on delete set null,
  created_at timestamptz not null default timezone('utc'::text, now()),
  check (
    (deleted_at is null and body is not null and length(btrim(body)) between 1 and 4000)
    or (deleted_at is not null and body is null)
  ),
  check (sender_role <> 'staff' or sender_user_id is not null)
);

create index support_chat_messages_history_idx
  on public.support_chat_messages (thread_id, created_at desc, id desc);

create table public.support_chat_message_hides (
  id bigint generated by default as identity primary key,
  message_id uuid not null references public.support_chat_messages(id) on delete cascade,
  user_id uuid references public.users(id) on delete cascade,
  guest_thread_id uuid references public.support_chat_threads(id) on delete cascade,
  created_at timestamptz not null default timezone('utc'::text, now()),
  check ((user_id is null) <> (guest_thread_id is null))
);

create unique index support_chat_message_hides_user_uidx
  on public.support_chat_message_hides (message_id, user_id)
  where user_id is not null;
create unique index support_chat_message_hides_guest_uidx
  on public.support_chat_message_hides (message_id, guest_thread_id)
  where guest_thread_id is not null;

create table public.support_chat_guest_sessions (
  id uuid primary key default gen_random_uuid(),
  thread_id uuid not null references public.support_chat_threads(id) on delete cascade,
  token_hash text not null unique check (token_hash ~ '^[a-f0-9]{64}$'),
  realtime_key text not null unique check (realtime_key ~ '^[a-f0-9]{64}$'),
  expires_at timestamptz not null,
  last_used_at timestamptz not null default timezone('utc'::text, now()),
  created_at timestamptz not null default timezone('utc'::text, now())
);

create index support_chat_guest_sessions_thread_expiry_idx
  on public.support_chat_guest_sessions (thread_id, expires_at desc);

create table public.support_chat_recovery_challenges (
  id uuid primary key default gen_random_uuid(),
  thread_id uuid references public.support_chat_threads(id) on delete cascade,
  guest_email text not null check (
    guest_email = lower(btrim(guest_email))
    and guest_email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
  ),
  customer_name text not null check (length(btrim(customer_name)) between 1 and 120),
  code_hash text not null check (code_hash ~ '^[a-f0-9]{64}$'),
  attempt_count integer not null default 0 check (attempt_count between 0 and 5),
  expires_at timestamptz not null,
  consumed_at timestamptz,
  created_at timestamptz not null default timezone('utc'::text, now())
);

create index support_chat_recovery_challenges_recent_idx
  on public.support_chat_recovery_challenges (guest_email, created_at desc);

